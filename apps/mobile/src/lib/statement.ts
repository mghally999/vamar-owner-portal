/**
 * Monthly / yearly statement PDF generated on the device with expo-print (no server CPU).
 * IBM Plex Sans Arabic is embedded as base64 so Arabic renders identically everywhere.
 */
import { Asset } from 'expo-asset';
import * as FileSystem from 'expo-file-system/legacy';
import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import { formatAmount, formatDate, formatMonth, type Lang, type PlainDate } from '@vamar/shared';
import { CHEQUE_STATUS_LABEL } from '@vamar/shared';
import type { ChequeItem } from './types';

let fontCache: string | null = null;

async function fontBase64(): Promise<string> {
  if (fontCache) return fontCache;
  const asset = Asset.fromModule(
    require('../../../../packages/tokens/assets/fonts/IBMPlexSansArabic-Regular.woff2'),
  );
  await asset.downloadAsync();
  const uri = asset.localUri ?? asset.uri;
  fontCache = await FileSystem.readAsStringAsync(uri, { encoding: 'base64' });
  return fontCache;
}

export interface StatementInput {
  ownerName: string;
  periodLabel: string;
  cheques: ChequeItem[];
  lang: Lang;
  generatedOn: PlainDate;
}

export function statementHtml(input: StatementInput, font: string): string {
  const { lang } = input;
  const dir = lang === 'ar' ? 'rtl' : 'ltr';
  const t = (ar: string, en: string) => (lang === 'ar' ? ar : en);
  const total = input.cheques
    .filter((c) => c.status !== 'cancelled' && c.status !== 'replaced')
    .reduce((a, c) => a + (c.amountFils ?? 0), 0);
  const cleared = input.cheques
    .filter((c) => c.status === 'cleared')
    .reduce((a, c) => a + (c.amountFils ?? 0), 0);
  const rows = input.cheques
    .map(
      (c) => `<tr>
        <td class="n">${formatDate(c.dueDate as PlainDate, lang)}</td>
        <td>${lang === 'ar' ? c.buildingNameAr : c.buildingNameEn} ${c.unitNo}</td>
        <td>${c.tenantName}</td>
        <td class="n">${c.chequeNo ?? '—'}</td>
        <td>${c.bankName ?? '—'}</td>
        <td class="n amt">${c.amountFils === null ? '—' : formatAmount(c.amountFils, lang)}</td>
        <td>${CHEQUE_STATUS_LABEL[c.status][lang]}</td>
      </tr>`,
    )
    .join('');
  return `<!doctype html><html lang="${lang}" dir="${dir}"><head><meta charset="utf-8">
<style>
@font-face{font-family:'Plex';src:url(data:font/woff2;base64,${font}) format('woff2')}
body{font-family:'Plex',sans-serif;color:#162842;margin:28px;font-size:12px}
h1{font-size:20px;margin:0 0 4px;font-weight:600}
.muted{color:#5f7180}
.hero{font-size:26px;font-weight:600;margin:18px 0 2px;font-variant-numeric:tabular-nums}
table{width:100%;border-collapse:collapse;margin-top:18px}
th,td{padding:7px 6px;border-bottom:1px solid #dcd7cc;text-align:start;vertical-align:top}
th{font-size:11px;color:#5f7180;font-weight:500}
.n{font-variant-numeric:tabular-nums}
.amt{white-space:nowrap}
.foot{margin-top:24px;font-size:10px;color:#5f7180}
</style></head><body>
<h1>${t('كشف حساب الشيكات', 'Cheque statement')}</h1>
<div class="muted">${input.ownerName} · ${input.periodLabel}</div>
<div class="hero">${formatAmount(total, lang)}</div>
<div class="muted">${t('تم صرفه', 'Cleared')}: ${formatAmount(cleared, lang)} · ${t('عدد الشيكات', 'Cheques')}: ${input.cheques.length}</div>
<table><thead><tr>
<th>${t('التاريخ', 'Date')}</th><th>${t('الوحدة', 'Unit')}</th><th>${t('المستأجر', 'Tenant')}</th><th>${t('رقم الشيك', 'Cheque no.')}</th><th>${t('البنك', 'Bank')}</th><th>${t('المبلغ', 'Amount')}</th><th>${t('الحالة', 'Status')}</th>
</tr></thead><tbody>${rows}</tbody></table>
<div class="foot">${t('صادر من بوابة ملاك فامار بتاريخ', 'Generated by the Vamar owner portal on')} ${formatDate(input.generatedOn, lang)}. ${t('المبالغ تمثل حصة المالك من الإيجار الإجمالي.', 'Amounts are the owner’s share of the gross rent.')}</div>
</body></html>`;
}

export async function shareStatement(input: StatementInput): Promise<void> {
  const html = statementHtml(input, await fontBase64());
  const { uri } = await Print.printToFileAsync({ html, base64: false });
  const name = `vamar-statement-${input.periodLabel.replace(/\s+/g, '-')}.pdf`;
  const dest = `${FileSystem.cacheDirectory ?? ''}${name}`;
  try {
    await FileSystem.moveAsync({ from: uri, to: dest });
  } catch {
    // keep original uri
  }
  if (await Sharing.isAvailableAsync())
    await Sharing.shareAsync(dest, { mimeType: 'application/pdf', UTI: 'com.adobe.pdf' });
}

export function periodLabel(kind: 'month' | 'year', today: PlainDate, lang: Lang): string {
  return kind === 'month' ? formatMonth(today, lang) : today.slice(0, 4);
}
