import type { PlainDate } from '@vamar/shared';
import { periodLabel, shareStatement, statementHtml, type StatementInput } from '@/lib/statement';
import { asset, fileSystem, fontAsset, print, sharing } from '@/test/native';
import { cheque } from '@/test/fixtures';

const cheques = [
  cheque({ id: 'a', status: 'cleared', amountFils: 2_500_000 }),
  cheque({ id: 'b', status: 'upcoming', amountFils: 1_000_050, chequeNo: null, bankName: null }),
  cheque({ id: 'c', status: 'cancelled', amountFils: 9_000_000 }),
  cheque({ id: 'd', status: 'replaced', amountFils: 8_000_000 }),
  cheque({ id: 'e', status: 'bounced', amountFils: null }),
];

function input(over: Partial<StatementInput> = {}): StatementInput {
  return {
    ownerName: 'Salem Al Kaabi',
    periodLabel: 'October 2026',
    cheques,
    lang: 'en',
    generatedOn: '2026-10-25',
    ...over,
  };
}

describe('statement HTML', () => {
  it('totals the live cheques, shows what cleared and lists every cheque (English)', () => {
    const html = statementHtml(input(), "url(font.ttf) format('truetype')");
    expect(html).toContain('<html lang="en" dir="ltr">');
    expect(html).toContain("src:url(font.ttf) format('truetype')");
    expect(html).toContain('Salem Al Kaabi · October 2026');
    // Cancelled and replaced cheques are not money the owner expects.
    expect(html).toContain('<div class="hero">AED 35,000.50</div>');
    expect(html).toContain('Cleared: AED 25,000 · Cheques: 5');
    expect(html.match(/<tr>/g)).toHaveLength(6);
    expect(html).toContain('<td>Oasis Tower 1204</td>');
    expect(html).toContain('<td class="n">5 Oct 2026</td>');
    expect(html).toContain('<td class="n">—</td>');
    expect(html).toContain('<td class="n amt">—</td>');
    expect(html).toContain('<td>Bounced</td>');
    expect(html).toContain('Generated by the Vamar owner portal on 25 Oct 2026');
  });

  it('is right to left with Arabic labels in Arabic', () => {
    const html = statementHtml(input({ lang: 'ar', cheques: [cheques[0]!] }), 'x');
    expect(html).toContain('<html lang="ar" dir="rtl">');
    expect(html).toContain('كشف حساب الشيكات');
    expect(html).toContain('<td>برج الواحة 1204</td>');
    expect(html).toContain('25,000 درهم');
  });

  it('labels the period as the month or the year', () => {
    const today = '2026-10-25' as PlainDate;
    expect(periodLabel('month', today, 'en')).toBe('October 2026');
    expect(periodLabel('year', today, 'ar')).toBe('2026');
  });
});

describe('shareStatement', () => {
  it('prints a PDF with the embedded font, names it after the period and shares it', async () => {
    // First call in this file: the font is read from the bundled asset (no local copy yet).
    fontAsset.localUri = null;
    await shareStatement(input());
    expect(fontAsset.downloadAsync).toHaveBeenCalled();
    expect(fileSystem.readAsStringAsync).toHaveBeenCalledWith('asset://Almarai-Regular.ttf', {
      encoding: 'base64',
    });
    const [options] = print.printToFileAsync.mock.calls[0]!;
    expect(options.base64).toBe(false);
    expect(options.html).toContain("src:url(data:font/ttf;base64,Rk9OVA==) format('truetype')");
    expect(fileSystem.moveAsync).toHaveBeenCalledWith({
      from: 'file:///tmp/print-1.pdf',
      to: 'file:///cache/vamar-statement-October-2026.pdf',
    });
    expect(sharing.shareAsync).toHaveBeenCalledWith(
      'file:///cache/vamar-statement-October-2026.pdf',
      { mimeType: 'application/pdf', UTI: 'com.adobe.pdf' },
    );
  });

  it('reads the font only once', async () => {
    await shareStatement(input({ periodLabel: '2026' }));
    expect(asset.fromModule).not.toHaveBeenCalled();
    expect(fileSystem.readAsStringAsync).not.toHaveBeenCalled();
    expect(sharing.shareAsync).toHaveBeenCalledWith(
      'file:///cache/vamar-statement-2026.pdf',
      expect.anything(),
    );
  });

  it('still offers the PDF when it cannot be moved to the cache', async () => {
    fileSystem.moveAsync.mockRejectedValue(new Error('disk full'));
    fileSystem.cacheDirectory = null;
    await expect(shareStatement(input())).resolves.toBeUndefined();
    expect(sharing.shareAsync).toHaveBeenCalledTimes(1);
  });

  it('does not open a share sheet where sharing is unavailable', async () => {
    sharing.isAvailableAsync.mockResolvedValue(false);
    await shareStatement(input());
    expect(print.printToFileAsync).toHaveBeenCalled();
    expect(sharing.shareAsync).not.toHaveBeenCalled();
  });
});
