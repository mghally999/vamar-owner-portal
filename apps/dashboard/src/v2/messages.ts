export const v2Messages = { ar, en };

/** The lib i18n helpers plus `t` over the v2 dictionary. */
export function useV2() {
  const i18n = useI18n();
  const dict = v2Messages[i18n.lang];
  const t = useCallback(
    (key: V2MessageKey, vars?: Record<string, string | number>) => {
      let s: string = dict[key];
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
      return s;
    },
    [dict],
  );
  return { ...i18n, t, tv2: t, lib: i18n.t };
}
