// Emits dist/tokens.css: CSS custom properties for the dashboard (Tailwind v4 @theme consumes
// them). The default theme is on :root; the white theme under [data-theme="white"] and the dark
// palette under [data-theme="dark"] (kept for any web surface; the dashboard offers default and
// white).
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  brand,
  fontFamily,
  fontSize,
  neutral,
  radius,
  shadow,
  spacing,
  status,
  themes,
  type SemanticColors,
} from '../src/index.js';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'dist', 'tokens.css');

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
const lines: string[] = [];
const push = (name: string, value: string | number) => lines.push(`  --${name}: ${value};`);
const palette = (colors: SemanticColors, onDark: boolean) => {
  for (const [k, v] of Object.entries(colors)) push(`color-${kebab(k)}`, v);
  for (const [k, v] of Object.entries(status)) {
    push(`color-status-${k}`, onDark ? v.fgOnDark : v.fg);
    push(`color-status-${k}-bg`, onDark ? v.bgOnDark : v.bg);
  }
};

lines.push('/* Generated by packages/tokens/scripts/build-css.ts. Do not edit by hand. */');
lines.push(':root {');
push('font-sans', fontFamily.fallback);
for (const [k, v] of Object.entries(fontSize)) {
  push(`text-${k}`, `${v.size}px`);
  push(`text-${k}--line-height`, `${v.lineHeight}px`);
}
for (const [k, v] of Object.entries(spacing)) push(`spacing-${k}`, `${v}px`);
for (const [k, v] of Object.entries(radius)) push(`radius-${k}`, `${v}px`);
push('shadow-card', shadow.card.css);
push('color-brand-silver', brand.silver);
push('color-brand-slate', brand.primary);
for (const [k, v] of Object.entries(neutral)) push(`color-neutral-${k}`, v);
palette(themes.default, false);
lines.push('}');
lines.push('');
lines.push('[data-theme="white"] {');
palette(themes.white, false);
lines.push('}');
lines.push('');
lines.push('[data-theme="dark"] {');
palette(themes.dark, true);
lines.push('}');
lines.push('');

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join('\n'));
console.info(`wrote ${out}`);
