// Emits dist/tokens.css: CSS custom properties for the dashboard (Tailwind v4 @theme consumes
// them). Light values on :root; dark values are emitted under [data-theme="dark"] so the same
// file works for any web surface even though the dashboard itself is light only.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  dark,
  fontFamily,
  fontSize,
  light,
  neutral,
  radius,
  shadow,
  spacing,
  status,
} from '../src/index.js';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'dist', 'tokens.css');

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
const lines: string[] = [];
const push = (name: string, value: string | number) => lines.push(`  --${name}: ${value};`);

lines.push('/* Generated by packages/tokens/scripts/build-css.ts. Do not edit by hand. */');
lines.push(':root {');
push('font-sans', fontFamily.fallback);
for (const [k, v] of Object.entries(fontSize)) {
  push(`text-${k}`, `${v.size}px`);
  push(`text-${k}--line-height`, `${v.lineHeight}px`);
}
for (const [k, v] of Object.entries(spacing)) push(`spacing-${k}`, `${v}px`);
for (const [k, v] of Object.entries(radius)) push(`radius-${k}`, `${v}px`);
push('shadow-card', shadow.card.css);
for (const [k, v] of Object.entries(neutral)) push(`color-neutral-${k}`, v);
for (const [k, v] of Object.entries(light)) push(`color-${kebab(k)}`, v);
for (const [k, v] of Object.entries(status)) {
  push(`color-status-${k}`, v.fg);
  push(`color-status-${k}-bg`, v.bg);
}
lines.push('}');
lines.push('');
lines.push('[data-theme="dark"] {');
for (const [k, v] of Object.entries(dark)) push(`color-${kebab(k)}`, v);
for (const [k, v] of Object.entries(status)) {
  push(`color-status-${k}`, v.fgOnDark);
  push(`color-status-${k}-bg`, v.bgOnDark);
}
lines.push('}');
lines.push('');

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join('\n'));
console.info(`wrote ${out}`);
