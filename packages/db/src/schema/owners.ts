import { index, pgTable, text, uniqueIndex, uuid } from 'drizzle-orm/pg-core';
import { createdAt, id, instant } from './_common.js';
import { devicePlatform, lang, notificationType, ownerStatus, subjectType } from './enums.js';
import { staffUsers } from './staff.js';

export const owners = pgTable(
  'owners',
  {
    id: id(),
    nameAr: text().notNull(),
    nameEn: text().notNull(),
    /** Login identity: must match the Firebase phone exactly. */
    phoneE164: text('phone_e164').notNull().unique(),
    email: text(),
    preferredLang: lang().notNull().default('ar'),
    status: ownerStatus().notNull().default('invited'),
    createdBy: uuid().references(() => staffUsers.id),
    createdAt: createdAt(),
  },
  (t) => [index('owners_status_idx').on(t.status)],
);

export const devices = pgTable(
  'devices',
  {
    id: id(),
    ownerId: uuid()
      .notNull()
      .references(() => owners.id, { onDelete: 'cascade' }),
    /** Stable per-install identifier generated by the app. */
    deviceId: text().notNull(),
    platform: devicePlatform().notNull(),
    model: text().notNull().default(''),
    pushToken: text(),
    firstSeen: instant().notNull().defaultNow(),
    lastSeen: instant().notNull().defaultNow(),
    revokedAt: instant(),
  },
  (t) => [
    uniqueIndex('devices_owner_device_uq').on(t.ownerId, t.deviceId),
    index('devices_owner_idx').on(t.ownerId),
  ],
);

/** Refresh tokens. The token itself is never stored, only its SHA-256. */
export const sessions = pgTable(
  'sessions',
  {
    id: id(),
    subjectType: subjectType().notNull(),
    subjectId: uuid().notNull(),
    /** Owner sessions are bound to a device; staff sessions have null. */
    deviceId: text(),
    tokenHash: text().notNull().unique(),
    expiresAt: instant().notNull(),
    /** Previous session in the rotation chain; reuse of a rotated token revokes the chain. */
    rotatedFrom: uuid(),
    revokedAt: instant(),
    createdAt: createdAt(),
  },
  (t) => [
    index('sessions_subject_idx').on(t.subjectType, t.subjectId),
    index('sessions_expires_idx').on(t.expiresAt),
  ],
);

export const notificationLog = pgTable(
  'notification_log',
  {
    id: id(),
    ownerId: uuid()
      .notNull()
      .references(() => owners.id, { onDelete: 'cascade' }),
    type: notificationType().notNull(),
    entityId: uuid().notNull(),
    /** `type:entityId:date`; the unique constraint makes cron re-runs idempotent. */
    dedupeKey: text().notNull().unique(),
    sentAt: instant().notNull().defaultNow(),
    /** Expo ticket status or error code, for support. */
    result: text().notNull().default(''),
  },
  (t) => [index('notification_log_owner_idx').on(t.ownerId, t.sentAt)],
);
